/// KhataPro · AES-256 (encrypt direction only) and CTS-free CTR mode.
///
/// Why hand-written: the key-wrapping codec must run in three environments —
/// inside Flutter on device, inside the bare-Dart verification harness, and
/// inside a future CLI restore tool that must decrypt a backup pack on a
/// machine with no Flutter installed. A pure implementation with no package
/// dependency is the only way all three work from one source.
///
/// Why encrypt-only: [AesCtr] is all this app needs, and CTR mode uses only the
/// forward cipher. That removes the inverse cipher, the inverse S-box, and the
/// InvMixColumns tables — roughly half the code, and the half where bugs hide.
///
/// Verification: `tool/aes_verify.dart` checks the FIPS-197 known-answer vectors
/// and a differential set generated by OpenSSL 3 (an independent
/// implementation). A wrong S-box produces output that looks random and
/// decrypts correctly *by itself*, so nothing in the app would ever notice —
/// only an external oracle catches that class of bug.
library;

import 'dart:typed_data';

/// AES-256 block cipher, encryption direction.
final class Aes256 {
  Aes256(List<int> key)
      : assert(key.length == 32, 'AES-256 needs a 32-byte key'),
        _roundKeys = _expandKey(key);

  static const int blockSize = 16;
  static const int keySize = 32;
  static const int _rounds = 14; // Nr for AES-256

  /// 15 round keys × 16 bytes, flattened (60 words).
  final Uint8List _roundKeys;

  /// Encrypts exactly one 16-byte block in place.
  void encryptBlock(Uint8List block, [int offset = 0]) {
    assert(block.length - offset >= 16, 'need a full block');
    final state = Uint8List(16);
    for (var i = 0; i < 16; i++) {
      state[i] = block[offset + i] ^ _roundKeys[i];
    }

    for (var round = 1; round < _rounds; round++) {
      _subBytes(state);
      _shiftRows(state);
      _mixColumns(state);
      _addRoundKey(state, round);
    }
    // Final round: no MixColumns.
    _subBytes(state);
    _shiftRows(state);
    _addRoundKey(state, _rounds);

    for (var i = 0; i < 16; i++) {
      block[offset + i] = state[i];
    }
  }

  void _addRoundKey(Uint8List state, int round) {
    final base = round * 16;
    for (var i = 0; i < 16; i++) {
      state[i] ^= _roundKeys[base + i];
    }
  }

  static void _subBytes(Uint8List state) {
    for (var i = 0; i < 16; i++) {
      state[i] = sBox[state[i]];
    }
  }

  /// The AES state is column-major: byte `4*c + r` is row r of column c.
  /// ShiftRows rotates row r left by r positions.
  static void _shiftRows(Uint8List s) {
    final t = Uint8List.fromList(s);
    for (var row = 1; row < 4; row++) {
      for (var col = 0; col < 4; col++) {
        s[4 * col + row] = t[4 * ((col + row) % 4) + row];
      }
    }
  }

  static void _mixColumns(Uint8List s) {
    for (var col = 0; col < 4; col++) {
      final i = col * 4;
      final a0 = s[i], a1 = s[i + 1], a2 = s[i + 2], a3 = s[i + 3];
      s[i] = _xtime(a0) ^ (_xtime(a1) ^ a1) ^ a2 ^ a3;
      s[i + 1] = a0 ^ _xtime(a1) ^ (_xtime(a2) ^ a2) ^ a3;
      s[i + 2] = a0 ^ a1 ^ _xtime(a2) ^ (_xtime(a3) ^ a3);
      s[i + 3] = (_xtime(a0) ^ a0) ^ a1 ^ a2 ^ _xtime(a3);
    }
  }

  /// Multiply by 2 in GF(2^8) modulo x⁸+x⁴+x³+x+1 (0x11B).
  static int _xtime(int value) {
    final shifted = (value << 1) & 0xFF;
    return (value & 0x80) != 0 ? shifted ^ 0x1B : shifted;
  }

  /// AES-256 key schedule: 60 words, Nk=8, Nr=14.
  static Uint8List _expandKey(List<int> key) {
    const nk = 8;
    const words = 4 * (_rounds + 1); // 60
    final w = Uint8List(words * 4);
    for (var i = 0; i < nk * 4; i++) {
      w[i] = key[i];
    }

    var rcon = 1;
    for (var i = nk; i < words; i++) {
      final base = i * 4;
      final previous = (i - 1) * 4;
      if (i % nk == 0) {
        // RotWord + SubWord + Rcon
        w[base] = sBox[w[previous + 1]] ^ rcon;
        w[base + 1] = sBox[w[previous + 2]];
        w[base + 2] = sBox[w[previous + 3]];
        w[base + 3] = sBox[w[previous]];
        rcon = _xtime(rcon);
      } else if (i % nk == 4) {
        // AES-256 only: an extra SubWord in the middle of the eight-word run.
        for (var k = 0; k < 4; k++) {
          w[base + k] = sBox[w[previous + k]];
        }
      } else {
        for (var k = 0; k < 4; k++) {
          w[base + k] = w[previous + k];
        }
      }
      for (var k = 0; k < 4; k++) {
        w[base + k] ^= w[base - nk * 4 + k];
      }
    }
    return w;
  }

  /// The S-box, built from its definition rather than copied from a table:
  /// `S(a) = affine(a⁻¹ in GF(2⁸))`. Generated once, lazily.
  static final Uint8List sBox = _buildSBox();

  static Uint8List _buildSBox() {
    final inverse = Uint8List(256);
    for (var i = 1; i < 256; i++) {
      inverse[i] = _gfInverse(i);
    }
    inverse[0] = 0; // 0 has no inverse; S(0) = 0x63 by the affine map alone

    final box = Uint8List(256);
    for (var i = 0; i < 256; i++) {
      final x = inverse[i];
      // Affine transform: b ^= rotl(b, 1..4), then XOR 0x63.
      final y = x ^ _rotl8(x, 1) ^ _rotl8(x, 2) ^ _rotl8(x, 3) ^ _rotl8(x, 4) ^ 0x63;
      box[i] = y & 0xFF;
    }
    return box;
  }

  static int _rotl8(int value, int bits) =>
      ((value << bits) | (value >> (8 - bits))) & 0xFF;

  /// Multiplicative inverse in GF(2⁸) by square-and-multiply (a²⁵⁴ = a⁻¹).
  static int _gfInverse(int a) {
    var result = 1;
    var base = a;
    var exponent = 254;
    while (exponent > 0) {
      if ((exponent & 1) != 0) result = _gfMultiply(result, base);
      base = _gfMultiply(base, base);
      exponent >>= 1;
    }
    return result;
  }

  static int _gfMultiply(int a, int b) {
    var result = 0;
    var x = a;
    var y = b;
    while (y > 0) {
      if ((y & 1) != 0) result ^= x;
      x = _xtime(x);
      y >>= 1;
    }
    return result & 0xFF;
  }
}

/// AES-256 in counter mode.
///
/// The counter is the full 128-bit big-endian block, incremented as an integer
/// — the same convention as OpenSSL's `aes-256-ctr` and NIST SP 800-38A, so the
/// differential vectors apply directly.
///
/// **CTR provides confidentiality only.** It is never used alone here: callers
/// use [AesCtrHmac], which is encrypt-then-MAC and therefore authenticated.
final class AesCtr {
  AesCtr({required List<int> key, required List<int> iv})
      : assert(iv.length == 16, 'CTR IV must be 16 bytes'),
        _cipher = Aes256(key),
        _counter = Uint8List.fromList(iv);

  final Aes256 _cipher;
  final Uint8List _counter;
  final Uint8List _keystream = Uint8List(Aes256.blockSize);
  int _keystreamOffset = Aes256.blockSize; // forces a refill on first use

  /// XORs [length] bytes of keystream into `data[offset..]`. Symmetric: the
  /// same call encrypts and decrypts.
  void apply(Uint8List data) {
    for (var i = 0; i < data.length; i++) {
      if (_keystreamOffset == Aes256.blockSize) {
        // Copy the counter, THEN encrypt the copy. Encrypting `_counter` in
        // place would overwrite the counter with its own ciphertext, so every
        // block after the first would use a nonsense counter — a bug that
        // survives every self-consistency test and is only visible against an
        // external reference. (Caught by tool/aes_verify.dart.)
        _keystream.setAll(0, _counter);
        _cipher.encryptBlock(_keystream);
        _incrementCounter();
        _keystreamOffset = 0;
      }
      data[i] ^= _keystream[_keystreamOffset++];
    }
  }

  void _incrementCounter() {
    for (var i = 15; i >= 0; i--) {
      _counter[i] = (_counter[i] + 1) & 0xFF;
      if (_counter[i] != 0) return;
    }
    // Counter wrapped: 2¹²⁸ blocks. Unreachable in practice (an exabyte), and
    // silently reusing keystream would be catastrophic — so refuse instead.
    throw StateError('AES-CTR counter exhausted');
  }
}
